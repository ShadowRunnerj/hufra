        private static int FindSeparator(string line)
        {
            for (int i = 0; i < line.Length; i++)
                if (line[i] == '=' && (i == 0 || line[i - 1] != '\\')) return i;
            return -1;
        }

        public static List<TextEntry> ReadCapture(string root)
        {
            var list = new List<TextEntry>();
            string path = Path.Combine(root, CaptureRel);
            if (!File.Exists(path)) return list;

            var seen = new HashSet<string>();
            foreach (var raw in File.ReadAllLines(path, Encoding.UTF8))
            {
                if (raw.Length == 0 || raw.StartsWith("//")) continue;
                int sep = FindSeparator(raw);
                if (sep <= 0) continue;
                string key = raw.Substring(0, sep).Replace("\\=", "=");
                if (key.Length < 2 || !key.Any(char.IsLetter) || !seen.Add(key)) continue;
                list.Add(new TextEntry
                {
                    SourceFile = CaptureRel,
                    LocationKey = "xunity:" + list.Count,
                    OriginalText = key,
                    HasPlaceholders = LooseTextExtractor.ContainsPlaceholder(key),
                });
            }
            return list;
        }

        public static bool WriteCapture(string root, IReadOnlyList<TextEntry> entries)
        {
            string path = Path.Combine(root, CaptureRel);
            if (!File.Exists(path)) return false;

            bool shape = AppSettingsStore.GetShapeArabic();
            var map = new Dictionary<string, string>();
            foreach (var e in entries.Where(e => e.IsApproved && !string.IsNullOrWhiteSpace(e.TranslatedText)))
            {
                string v = shape ? ArabicShaper.PrepareForLtrEngine(e.TranslatedText) : e.TranslatedText;
                map[e.OriginalText] = v.Replace("\r\n", "\\n").Replace("\n", "\\n").Replace("=", "\\=");
            }

            var lines = File.ReadAllLines(path, Encoding.UTF8).ToList();
            var present = new HashSet<string>();
            for (int i = 0; i < lines.Count; i++)
            {
                int sep = FindSeparator(lines[i]);
                if (sep <= 0 || lines[i].StartsWith("//")) continue;
                string key = lines[i].Substring(0, sep).Replace("\\=", "=");
                if (map.TryGetValue(key, out var tr)) { lines[i] = lines[i].Substring(0, sep) + "=" + tr; present.Add(key); }
            }
            foreach (var kv in map.Where(k => !present.Contains(k.Key)))
                lines.Add(kv.Key.Replace("=", "\\=") + "=" + kv.Value);

            File.WriteAllText(path, string.Join("\r\n", lines) + "\r\n", new UTF8Encoding(false));
            return true;
        }
