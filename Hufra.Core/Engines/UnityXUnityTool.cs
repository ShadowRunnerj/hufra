    /// <summary>
    /// تعريب Unity "حقيقي" بدون تعديل ملفات assets: يركّب BepInEx 5 + XUnity.AutoTranslator داخل مجلد اللعبة (Mono فقط).
    /// الأداة تلتقط نصوص اللعبة أثناء تشغيلها في ملف ترجمة (_AutoGeneratedTranslations.txt)، وحُفرة يقرأها ويترجمها
    /// ويكتب الترجمة العربية فيه، فتظهر داخل اللعبة. الأدوات تُنزَّل من GitHub الرسمي.
    ///
    /// حدود: ألعاب IL2CPP غير مدعومة هنا. خطوط TextMeshPro قد تحتاج خط TMP (assetbundle) ليظهر العربي؛
    /// ويُضبط خط النظام Tahoma للنصوص من نوع UGUI/IMGUI.
    /// </summary>
    public static class UnityXUnityTool
    {
        public const string CaptureRel = @"BepInEx\Translation\ar\Text\_AutoGeneratedTranslations.txt";
        private const string ConfigRel = @"BepInEx\config\AutoTranslatorConfig.ini";

        private static string DataDir(string root) =>
            Directory.GetDirectories(root, "*_Data").FirstOrDefault();

        public static UnityToolStatus GetStatus(string root)
        {
            var s = new UnityToolStatus();
            try
            {
                string data = DataDir(root);
                s.IsUnity = data != null && File.Exists(Path.Combine(root, "UnityPlayer.dll"));
                if (!s.IsUnity) return s;

                s.IsIl2Cpp = File.Exists(Path.Combine(root, "GameAssembly.dll"));
                s.Arch = DetectArch(root, data);
                s.Installed = Directory.Exists(Path.Combine(root, "BepInEx", "plugins")) &&
                              Directory.GetFiles(Path.Combine(root, "BepInEx"), "XUnity.AutoTranslator.Plugin.Core.dll", SearchOption.AllDirectories).Length > 0;
            }
            catch { }
            return s;
        }

        // يقرأ ترويسة PE لملف اللعبة التنفيذي: 0x8664 = x64، 0x14C = x86
        private static string DetectArch(string root, string dataDir)
        {
            string exeName = Path.GetFileName(dataDir).Replace("_Data", "") + ".exe";
            string exe = Path.Combine(root, exeName);
            if (!File.Exists(exe)) exe = Directory.GetFiles(root, "*.exe").FirstOrDefault(f => !Path.GetFileName(f).StartsWith("Unity", StringComparison.OrdinalIgnoreCase));
            if (exe == null) return "x64";
            try
            {
                using var fs = File.OpenRead(exe);
                var b = new byte[4096];
                int n = fs.Read(b, 0, b.Length);
                int pe = BitConverter.ToInt32(b, 0x3C);
                if (pe + 6 < n) return BitConverter.ToUInt16(b, pe + 4) == 0x14C ? "x86" : "x64";
            }
            catch { }
            return "x64";
        }

        private static HttpClient NewClient()
        {
            var c = new HttpClient { Timeout = TimeSpan.FromMinutes(5) };
            c.DefaultRequestHeaders.UserAgent.ParseAdd("Hufra");
            c.DefaultRequestHeaders.Accept.ParseAdd("application/vnd.github+json");
            return c;
        }

        private static async Task<string> FindAssetUrlAsync(HttpClient http, string releasesUrl, Func<string, string, bool> tagOk, Func<string, bool> assetOk)
        {
            using var doc = JsonDocument.Parse(await http.GetStringAsync(releasesUrl));
            var root = doc.RootElement;
            var list = root.ValueKind == JsonValueKind.Array ? root.EnumerateArray().ToList() : new List<JsonElement> { root };
            foreach (var rel in list)
            {
                string tag = rel.GetProperty("tag_name").GetString() ?? "";
                bool pre = rel.TryGetProperty("prerelease", out var p) && p.GetBoolean();
                if (pre || !tagOk(tag, rel.TryGetProperty("name", out var nm) ? nm.GetString() : "")) continue;
                foreach (var a in rel.GetProperty("assets").EnumerateArray())
                {
                    string name = a.GetProperty("name").GetString() ?? "";
                    if (assetOk(name)) return a.GetProperty("browser_download_url").GetString();
                }
            }
            return null;
        }

        /// <summary>ينزّل ويركّب BepInEx + XUnity. يرجّع رسالة نجاح أو يرمي استثناء بسبب واضح.</summary>
        public static async Task<string> InstallAsync(string root, IProgress<string> progress = null)
        {
            var st = GetStatus(root);
            if (!st.IsUnity) throw new InvalidOperationException("هذا المجلد ليس لعبة Unity.");
            if (st.IsIl2Cpp) throw new InvalidOperationException("هذه لعبة IL2CPP (فيها GameAssembly.dll). التركيب التلقائي يدعم ألعاب Unity من نوع Mono فقط.");

            using var http = NewClient();
            string arch = st.Arch;

            progress?.Report("⏳ جاري البحث عن آخر إصدار من BepInEx...");
            string bepUrl = await FindAssetUrlAsync(http, "https://api.github.com/repos/BepInEx/BepInEx/releases?per_page=30",
                (tag, _) => tag.StartsWith("v5."),
                n => n.EndsWith(".zip", StringComparison.OrdinalIgnoreCase) && n.StartsWith("BepInEx_", StringComparison.OrdinalIgnoreCase) &&
                     n.Contains(arch, StringComparison.OrdinalIgnoreCase) && !n.Contains("unix", StringComparison.OrdinalIgnoreCase) &&
                     !n.Contains("linux", StringComparison.OrdinalIgnoreCase) && !n.Contains("macos", StringComparison.OrdinalIgnoreCase));
            if (bepUrl == null) throw new InvalidOperationException("ما لقيت ملف BepInEx المناسب (" + arch + ") في GitHub.");

            progress?.Report("⏳ جاري البحث عن XUnity.AutoTranslator...");
            string xuUrl = await FindAssetUrlAsync(http, "https://api.github.com/repos/bbepis/XUnity.AutoTranslator/releases/latest",
                (_, __) => true,
                n => n.EndsWith(".zip", StringComparison.OrdinalIgnoreCase) && n.StartsWith("XUnity.AutoTranslator-BepInEx-", StringComparison.OrdinalIgnoreCase) &&
                     !n.Contains("IL2CPP", StringComparison.OrdinalIgnoreCase));
            if (xuUrl == null) throw new InvalidOperationException("ما لقيت ملف XUnity.AutoTranslator المناسب في GitHub.");

            string tmp = Path.Combine(Path.GetTempPath(), "hufra_unity_" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(tmp);
            try
            {
                progress?.Report("⏳ جاري تنزيل BepInEx...");
                string bepZip = Path.Combine(tmp, "bepinex.zip");
                await File.WriteAllBytesAsync(bepZip, await http.GetByteArrayAsync(bepUrl));
                progress?.Report("⏳ جاري تنزيل XUnity.AutoTranslator...");
                string xuZip = Path.Combine(tmp, "xunity.zip");
                await File.WriteAllBytesAsync(xuZip, await http.GetByteArrayAsync(xuUrl));

                progress?.Report("⏳ جاري التركيب داخل مجلد اللعبة...");
                var targets = new List<(ZipArchiveEntry e, string rel)>();
                using var z1 = ZipFile.OpenRead(bepZip);
                using var z2 = ZipFile.OpenRead(xuZip);
                foreach (var z in new[] { z1, z2 })
                    foreach (var e in z.Entries)
                    {
                        if (string.IsNullOrEmpty(e.Name)) continue; // مجلد
                        string rel = e.FullName.Replace('/', '\\');
                        string full = Path.GetFullPath(Path.Combine(root, rel));
                        if (!full.StartsWith(Path.GetFullPath(root), StringComparison.OrdinalIgnoreCase)) continue; // حماية من المسارات الخبيثة
                        targets.Add((e, rel));
                    }

                var existing = targets.Select(t => t.rel).Where(r => File.Exists(Path.Combine(root, r))).ToList();
                if (File.Exists(Path.Combine(root, ConfigRel))) existing.Add(ConfigRel);
                BackupManager.BackupFiles(root, existing);

                var created = new List<string>();
                foreach (var (e, rel) in targets)
                {
                    string dst = Path.Combine(root, rel);
                    Directory.CreateDirectory(Path.GetDirectoryName(dst));
                    bool existed = File.Exists(dst);
                    e.ExtractToFile(dst, true);
                    if (!existed) created.Add(rel);
                }

                WriteConfig(root, created);
                BackupManager.RecordCreatedMany(root, created);

                bool ok = Directory.GetFiles(root, "XUnity.AutoTranslator.Plugin.Core.dll", SearchOption.AllDirectories).Length > 0 &&
                          File.Exists(Path.Combine(root, "winhttp.dll"));
                if (!ok) throw new InvalidOperationException("انتهى التركيب لكن ملفات الأداة الأساسية غير موجودة. راجع صلاحيات مجلد اللعبة.");

                return $"✅ تم تركيب BepInEx + XUnity ({targets.Count} ملف). الخطوة التالية: شغّل اللعبة وتنقّل في القوائم والحوارات، ثم أغلقها واضغط «استخراج النصوص».";
            }
            finally
            {
                try { Directory.Delete(tmp, true); } catch { }
            }
        }

        private static void WriteConfig(string root, List<string> created)
        {
            string path = Path.Combine(root, ConfigRel);
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            bool existed = File.Exists(path);
            // Endpoint=PassthroughTranslate: يلتقط النصوص بدون ترجمة خارجية. OverrideFont: خط النظام (فيه أشكال العرض العربية) لنصوص UGUI.
            File.WriteAllText(path,
                "[Service]\r\nEndpoint=PassthroughTranslate\r\nFallbackEndpoint=\r\n\r\n" +
                "[General]\r\nLanguage=ar\r\nFromLanguage=en\r\n\r\n" +
                "[Behaviour]\r\nOverrideFont=Tahoma\r\n\r\n" +
                "[Files]\r\nOutputFile=Translation\\{Lang}\\Text\\_AutoGeneratedTranslations.txt\r\n",
                new UTF8Encoding(false));
            if (!existed) created.Add(ConfigRel);
        }

